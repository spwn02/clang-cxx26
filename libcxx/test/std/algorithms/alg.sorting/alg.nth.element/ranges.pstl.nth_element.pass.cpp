// UNSUPPORTED: c++03, c++11, c++14, c++17, c++20, c++23
// UNSUPPORTED: libcpp-has-no-incomplete-pstl
#include <algorithm>
#include <array>
#include <cassert>
#include <execution>
template <class P> void test(P&& p) {
  std::array<int, 5> a{5, 1, 4, 2, 3};
  auto mid = a.begin() + 2;
  assert(std::ranges::nth_element(p, a, mid) == a.end());
  assert(*mid == 3);
  std::nth_element(p, a.begin(), mid, a.end());
  assert(*mid == 3);
}
int main(int, char**) { test(std::execution::seq); test(std::execution::par); test(std::execution::par_unseq); test(std::execution::unseq); }
